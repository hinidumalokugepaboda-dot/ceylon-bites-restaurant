export const createItemPortions = (id: string, price: number, category: MenuCategory): ItemPortion[] => {
  if (category === 'drinks' || category === 'desserts') {
    return [
      {
        id: `${id}-portion-r`,
        portionName: 'Regular (R)',
        portionCode: 'R',
        price: price,
        servesCount: 1,
        description: 'Single Serving (1 Person)'
      }
    ];
  }

  if (category === 'sharing') {
    return [
      {
        id: `${id}-portion-m`,
        portionName: 'Medium (M)',
        portionCode: 'M',
        price: Math.round((price * 0.75) / 50) * 50,
        servesCount: 2,
        description: 'Sharing Platter (Serves 2)'
      },
      {
        id: `${id}-portion-l`,
        portionName: 'Large (L)',
        portionCode: 'L',
        price: price,
        servesCount: 4,
        description: 'Full Feast Platter (Serves 4)'
      }
    ];
  }

  // Multi-tier portion sizing for all mains, devilled, seafood, bites
  const smallPrice = price;
  const mediumPrice = Math.round((price * 1.75) / 50) * 50;
  const largePrice = Math.round((price * 2.5) / 50) * 50;

  return [
    {
      id: `${id}-portion-s`,
      portionName: 'Small (S)',
      portionCode: 'S',
      price: smallPrice,
      servesCount: 1,
      description: 'Single Serving (Serves 1)'
    },
    {
      id: `${id}-portion-m`,
      portionName: 'Medium (M)',
      portionCode: 'M',
      price: mediumPrice,
      servesCount: 2,
      description: 'Standard 2-Person Sharing'
    },
    {
      id: `${id}-portion-l`,
      portionName: 'Large (L)',
      portionCode: 'L',
      price: largePrice,
      servesCount: 3,
      description: 'Family / Group Portion (Serves 3-4)'
    }
  ];
};

